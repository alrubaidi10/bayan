let LANG = localStorage.getItem('mizan_lang') || 'en';

function t(key, vars) {
  let s = (I18N[LANG] && I18N[LANG][key]) ?? I18N.en[key] ?? key;
  if (vars) for (const k of Object.keys(vars)) s = s.replaceAll('{' + k + '}', vars[k]);
  return s;
}
function setLang(l) {
  LANG = l === 'ar' ? 'ar' : 'en';
  localStorage.setItem('mizan_lang', LANG);
  document.documentElement.lang = LANG;
  document.documentElement.dir = LANG === 'ar' ? 'rtl' : 'ltr';
  document.title = (LANG === 'ar' ? 'بيان' : 'Bayan') + ' — ERP & Accounting';
}
function getLang() { return LANG; }

function fmtMoney(n, code) {
  const c = code || 'USD';
  const sym = window._currencies && window._currencies[c] ? window._currencies[c].symbol : c;
  try {
    const s = new Intl.NumberFormat(LANG === 'ar' ? 'ar-EG' : 'en-US', { maximumFractionDigits: 2, minimumFractionDigits: n % 1 !== 0 ? 2 : 0 }).format(n);
    return LANG === 'ar' ? `${s} ${sym}` : `${sym}${s}`;
  } catch { return n.toFixed(2); }
}
function fmtNum(n, digits = 2) {
  return new Intl.NumberFormat(LANG === 'ar' ? 'ar-EG' : 'en-US', { maximumFractionDigits: digits }).format(n);
}
function fmtDate(iso) {
  if (!iso) return '—';
  const d = new Date(iso.length === 10 ? iso + 'T00:00:00' : iso);
  return d.toLocaleDateString(LANG === 'ar' ? 'ar' : 'en-US', { year: 'numeric', month: 'short', day: 'numeric' });
}
