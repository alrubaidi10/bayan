/* debounce */
function debounce(fn, ms) { let tm; return (...a) => { clearTimeout(tm); tm = setTimeout(() => fn(...a), ms); }; }

/* close the topmost open modal */
function closeModal() {
  const root = document.getElementById('modal-root');
  const last = root && root.lastElementChild;
  if (last) last.remove();
}

