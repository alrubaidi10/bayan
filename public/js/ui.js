/* ---- toasts ---- */
function toast(msg, type = 'ok') {
  const tEl = el(`<div class="toast ${type}">${icon(type === 'err' ? 'alert' : 'check')}<span>${esc(msg)}</span></div>`);
  document.getElementById('toast-root').appendChild(tEl);
  setTimeout(() => { tEl.style.opacity = '0'; tEl.style.transition = 'opacity .3s'; }, 2800);
  setTimeout(() => tEl.remove(), 3200);
}

/* ---- modals ---- */
function modal({ title, body, wide, narrow, onOpen }) {
  const root = document.getElementById('modal-root');
  const overlay = el(`<div class="modal-overlay"><div class="modal ${wide ? 'wide' : ''} ${narrow ? 'narrow' : ''}">
    <div class="modal-head"><h3>${esc(title)}</h3><div class="spacer"></div>
    <button class="modal-x" title="${esc(t('close'))}">✕</button></div>
    <div class="modal-body"></div></div></div>`);
  root.appendChild(overlay);
  const bodyEl = overlay.querySelector('.modal-body');
  const close = () => overlay.remove();
  overlay.querySelector('.modal-x').onclick = close;
  overlay.addEventListener('mousedown', e => { if (e.target === overlay) close(); });
  if (onOpen) onOpen(bodyEl, close);
  return { el: overlay, bodyEl, close };
}
function confirmDlg(message, title) {
  return new Promise(resolve => {
    const m = modal({
      title: title || t('confirm'), narrow: true,
      onOpen(body, close) {
        body.innerHTML = `<p style="margin:4px 0 6px">${esc(message)}</p>
          <div style="display:flex;justify-content:flex-end;gap:10px;margin-top:16px">
          <button class="btn" data-a="no">${esc(t('cancel'))}</button>
          <button class="btn primary" data-a="yes">${esc(t('confirm'))}</button></div>`;
        body.querySelector('[data-a=no]').onclick = () => { close(); resolve(false); };
        body.querySelector('[data-a=yes]').onclick = () => { close(); resolve(true); };
      },
    });
  });
}

